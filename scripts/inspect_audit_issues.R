library(sf)
library(dplyr)
b <- st_read("data/raw/boundaries/salb_2018.geojson", quiet = TRUE) |>
  filter(adm1nm %in% c("Nord-Kivu", "Sud-Kivu", "Ituri"))
e <- read.csv("outputs/week_1/audit/event_ledger.csv")
ambiguous <- e |> filter(match_count > 1, type_of_violence == 3, year >= 2015)
matches <- st_intersects(st_as_sf(ambiguous, coords = c("longitude", "latitude"), crs = 4326), b)
ambiguous$matches <- vapply(matches, function(x) paste(b$adm2nm[x], collapse = " / "), character(1))
write.csv(ambiguous, "outputs/week_1/audit/ambiguous_event_matches.csv", row.names = FALSE)
print(count(ambiguous, matches))
